import { palette } from '../assets/color-theme.js';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { profile, projects, experience, education, skills, personalNotes } from '../assets/content.js';
import { floorContent } from '../assets/floor-content.js';
import { renderStory, renderGallery, renderProjectStatus } from '../assets/project-story.js';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const page = resolve(root, 'reading.html');
const site = 'https://bshwao.github.io/';
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const list = items => `<ul>\n${items.map(item => `          <li>${escape(item)}</li>`).join('\n')}\n        </ul>`;
const link = (href, label) => `<a href="${escape(href)}">${escape(label)}</a>`;

export function renderReadingPage() {
  const person = {
    '@context': 'https://schema.org',
    '@type': 'Person',
    '@id': `${site}#eric-hsu`,
    name: profile.name,
    url: site,
    sameAs: [profile.github, profile.linkedin],
    email: `mailto:${profile.email}`,
    affiliation: { '@type': 'CollegeOrUniversity', name: profile.university },
  };
  return `<!doctype html>
<!-- Generated by scripts/reading.mjs from assets/content.js and assets/floor-content.js. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="${palette.paper}">
  <title>${escape(profile.name)} — Portfolio reading view</title>
  <meta name="description" content="${escape(`${profile.name}'s projects, engineering experience, education, skills, and contact information. Electrical engineering at ${profile.university}, ${profile.location}.`)}">
  <meta property="og:title" content="${escape(profile.name)} — Portfolio reading view">
  <meta property="og:description" content="Projects, experience, education, skills, and contact information in a complete, accessible portfolio.">
  <meta property="og:type" content="profile">
  <meta property="og:url" content="${site}reading.html">
  <meta property="og:image" content="${site}assets/social-preview.png">
  <meta property="og:image:width" content="1280">
  <meta property="og:image:height" content="720">
  <meta property="og:image:alt" content="Eric Hsu — Electrical engineering at McGill, beside a dark stepped tower in a sunset city.">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="${site}assets/social-preview.png">
  <meta name="twitter:image:alt" content="Eric Hsu — Electrical engineering at McGill, beside a dark stepped tower in a sunset city.">
  <link rel="canonical" href="${site}reading.html">
  <link rel="icon" type="image/svg+xml" href="./assets/favicon.svg">
  <link rel="stylesheet" href="./assets/reading.css">
  <link rel="stylesheet" href="./assets/project-story.css">
  <link rel="stylesheet" href="./assets/theme.css">
  <link rel="stylesheet" href="./assets/color-system.css">
  <script type="application/ld+json">${JSON.stringify(person).replace(/</g, '\\u003c')}</script>
</head>
<body>
  <a class="skip-link" href="#portfolio">Skip to portfolio</a>
  <div class="reading-sheet">
    <header class="reading-header">
      <a class="drawing-label" href="./index.html">E.H. / Structures &amp; systems <span aria-hidden="true">↗</span></a>
      <p class="drawing-label">Portfolio / Reading view</p>
      <h1>${escape(profile.name)}</h1>
      <p class="intro">Electrical engineering at ${escape(profile.university)}.<br>Circuits, code, and the systems they make together.</p>
      <p class="coordinates">${escape(profile.location)} · ${escape(profile.graduation)}</p>
      <div class="header-links">${link(`mailto:${profile.email}`, 'Email')} ${link(profile.github, 'GitHub')} ${link(profile.linkedin, 'LinkedIn')} <a href="./assets/eric-hsu-resume.pdf" download="Eric-Hsu-Resume.pdf">Download résumé <span class="file-type">PDF</span></a></div>
      <nav aria-label="Portfolio sections">
        <a href="#about">01 About</a><a href="#projects">02 Projects</a><a href="#experience">03 Experience</a><a href="#education">04 Education</a><a href="#skills">05 Skills</a><a href="#contact">06 Contact</a>
      </nav>
    </header>

    <main id="portfolio">
      <section id="about" aria-labelledby="about-title">
        <p class="section-number" aria-hidden="true">01 / Orientation</p>
        <h2 id="about-title">About</h2>
        ${floorContent.about.rooms[0].paragraphs.map(text => `<p>${escape(text)}</p>`).join('\n        ')}
        <div class="personal-notes">${personalNotes.map(note => `<article><h3>${escape(note.title)}</h3><p>${escape(note.description)}</p></article>`).join('\n        ')}</div>
      </section>

      <section id="projects" aria-labelledby="projects-title">
        <p class="section-number" aria-hidden="true">02 / Selected work</p>
        <h2 id="projects-title">Projects</h2>
${projects.map(project => `        <article class="portfolio-entry" id="project-${escape(project.id)}">
          <div class="entry-heading"><h3>${escape(project.title)}</h3>${project.year ? `<p class="entry-date">${escape(project.year)}</p>` : ''}</div>
          ${renderProjectStatus(project.status)}
          <p class="entry-context">${escape(project.category)}</p>
          <p>${escape(project.description)}</p>
          ${renderStory(project.story)}
          ${list(project.bullets)}
          <p class="technology"><span>Technologies</span> ${escape(project.stack.join(' · '))}</p>
          ${renderGallery(project.images)}
          <p>${link(project.url, `View ${project.title} source`)} <span aria-hidden="true">↗</span></p>
          ${project.links?.length ? `<div class="project-additional-links">${project.links.map(item => link(item.href, item.label)).join('')}</div>` : ''}
        </article>`).join('\n')}
      </section>

      <section id="experience" aria-labelledby="experience-title">
        <p class="section-number" aria-hidden="true">03 / Engineering in practice</p>
        <h2 id="experience-title">Experience</h2>
${experience.map(item => `        <article class="portfolio-entry">
          <div class="entry-heading"><h3>${escape(item.organization)}</h3><p class="entry-date">${escape(item.period)}</p></div>
          <p class="entry-context">${escape(item.role)} · ${escape(item.location)}</p>
          ${list(item.bullets)}
        </article>`).join('\n')}
      </section>

      <section id="education" aria-labelledby="education-title">
        <p class="section-number" aria-hidden="true">04 / Academic archive</p>
        <h2 id="education-title">Education</h2>
${education.map(item => `        <article class="portfolio-entry">
          <div class="entry-heading"><h3>${escape(item.school)}</h3><p class="entry-date">${escape(item.period)}</p></div>
          <p class="entry-context">${escape(item.qualification)}</p>
          <p>${escape(item.detail)}</p>
        </article>`).join('\n')}
      </section>

      <section id="skills" aria-labelledby="skills-title">
        <p class="section-number" aria-hidden="true">05 / Technical reference</p>
        <h2 id="skills-title">Skills</h2>
        <dl class="skill-groups">
${skills.map(group => `          <div><dt>${escape(group.label)}</dt><dd>${escape(group.items.join(' · '))}</dd></div>`).join('\n')}
        </dl>
      </section>

      <section id="contact" aria-labelledby="contact-title">
        <p class="section-number" aria-hidden="true">06 / Correspondence</p>
        <h2 id="contact-title">Contact</h2>
        <p>Based in ${escape(profile.location)}. Find my work, get in touch, or download the complete résumé.</p>
        <ul class="contact-list">
          <li><span>Email</span> ${link(`mailto:${profile.email}`, profile.email)}</li>
          <li><span>GitHub</span> ${link(profile.github, profile.github.replace('https://', ''))}</li>
          <li><span>LinkedIn</span> ${link(profile.linkedin, profile.name)}</li>
          <li><span>Résumé</span> <a href="./assets/eric-hsu-resume.pdf" download="Eric-Hsu-Resume.pdf">Download résumé (PDF)</a></li>
        </ul>
      </section>
    </main>

    <footer><p class="drawing-label">E.H. / Complete portfolio</p><a href="./index.html">Explore the architectural portfolio <span aria-hidden="true">↗</span></a><a href="#portfolio">Back to top ↑</a></footer>
  </div>
</body>
</html>
`.replace(/^[ \t]+$/gm, '');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderReadingPage();
  if (process.argv.includes('--check')) {
    const actual = await readFile(page, 'utf8').catch(() => '');
    if (actual !== expected) {
      console.error('reading.html is missing or out of date. Run node scripts/reading.mjs.');
      process.exitCode = 1;
    } else console.log('Static reading portfolio matches the shared content.');
  } else {
    await writeFile(page, expected, 'utf8');
    console.log('Generated reading.html from the shared portfolio content.');
  }
}
