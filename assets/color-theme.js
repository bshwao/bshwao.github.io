export const roomAccents = [palette.teal, palette.coral, palette.blue, palette.rose];

export function themeCSS() {
  const variables = Object.entries(palette).map(([key, value]) => `  --${key}: ${value};`).join('\n');
  const sections = Object.entries(sectionColors).map(([id, colors]) =>
    `[data-section="${id}"], [data-section-theme="${id}"], #${id === 'resume' ? 'education' : id} { --accent: ${colors.accent}; --accent-ink: ${colors.ink}; --accent-tint: ${colors.tint}; }`).join('\n');
  const channels = hex => [1, 3, 5].map(start => parseInt(hex.slice(start, start + 2), 16)).join(',');
  return `/* Generated by scripts/theme.mjs from assets/color-theme.js. */\n:root {\n${variables}\n  --raised-rgb: ${channels(palette.raised)}; --paper-rgb: ${channels(palette.paper)}; --ink-rgb: ${channels(palette.ink)};\n  --soft-ink: var(--muted); --blue-ink: #435b76;\n  --accent: var(--teal); --accent-ink: #365e57; --accent-tint: #dbe8df;\n}\n${sections}\n`;
}
